#!/usr/bin/env node
// Write the example programs of examples/ into public/index.html.
//
// Usage: node scripts/examples.mjs [--check]
//
// examples/index.json lists the examples. Each has a program, ID.hs, and the
// output that the program printed, ID.out. scripts/run-examples.sh checks the
// output with aihc. This script colors the source and writes the markup
// between the two "examples" comments of the page. With --check it changes
// nothing, and fails when the page is not up to date.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { escape, highlight } from "../public/highlight.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const page = join(root, "public/index.html");
const begin = "<!-- examples:begin. Generated by scripts/examples.mjs from examples/. Do not edit. -->";
const end = "<!-- examples:end -->";

const examples = JSON.parse(await readFile(join(root, "examples/index.json"), "utf8"));
const tabs = [];
const panels = [];
for (const { id, title, note } of examples) {
  const source = (await readFile(join(root, "examples", id + ".hs"), "utf8")).trimEnd();
  const output = (await readFile(join(root, "examples", id + ".out"), "utf8")).trimEnd();
  tabs.push(`        <button role="tab" id="tab-ex-${id}" aria-controls="panel-ex-${id}">${escape(title)}</button>`);
  panels.push(`      <div class="panel example" role="tabpanel" id="panel-ex-${id}" aria-labelledby="tab-ex-${id}" data-example="${id}">
        <h3>${escape(title)}</h3>
        <div class="example-grid">
          <pre class="example-code"><code>${highlight(source)}</code></pre>
          <div class="example-run">
            <p class="example-note">${escape(note)}</p>
            <pre class="example-out"><code><span class="t-prompt">%</span> aihc build ${id}.hs
<span class="t-prompt">%</span> ./${id}
<span class="example-stdout">${escape(output)}</span></code></pre>
          </div>
        </div>
      </div>`);
}
const block = `${begin}
    <div class="tabbox examples reveal" data-tabs>
      <div class="tablist" role="tablist" aria-label="Example program">
${tabs.join("\n")}
      </div>
${panels.join("\n")}
    </div>
    ${end}`;

const html = await readFile(page, "utf8");
const from = html.indexOf(begin);
const to = html.indexOf(end);
if (from < 0 || to < from) throw new Error("public/index.html has no examples block.");
const next = html.slice(0, from) + block + html.slice(to + end.length);
if (process.argv.includes("--check")) {
  if (next !== html) {
    console.error("public/index.html is not up to date. Run: node scripts/examples.mjs");
    process.exit(1);
  }
} else if (next !== html) {
  await writeFile(page, next);
  console.log("Wrote the examples to public/index.html.");
}
